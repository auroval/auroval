#!/usr/bin/env python3
"""Derive the website's colour tokens from the theme's own rule, not by hand.

docs/decisions/b1-brand-hue.md chose one fixed brand hue, 330 deg, and named
the debt that choice creates:

    A second palette layer now exists and can drift. [...] if ACCENT_C_CAP, the
    lightness band or the contrast floor ever change, the website keeps the old
    hexes silently.

This script is that debt paid. The site's :root block is generated by the same
`build_palette()` the theme calls, so the two layers cannot disagree about what
a palette is -- only about which hue they were given, which is exactly the
difference B1 decided to have.

Why not `nightshade-pack`: that tool derives a palette *for a scene*, from one
canonical frame, and requires media. The brand has no media. That is not an
inconvenience to work around, it is the content of B1 -- the product follows
its wallpaper and the brand does not follow anything -- so the two live in
separate tools rather than one tool with a flag meaning "pretend there is no
image".

Two files come out, for the same reason: both are build_palette() output that
would otherwise be pasted into a stylesheet or a script and left to rot.

    site/sass/_tokens.scss   the brand palette at BRAND_HUE
    site/static/gamut.json   the accent curve the site plots, all 120 hues

Usage:
    python3 tools/scene-check/emit_web_tokens.py --write
    python3 tools/scene-check/emit_web_tokens.py --check    # CI
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import colourmath as cm
import scene_check as sc

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "site/sass/_tokens.scss"
CURVE = ROOT / "site/static/gamut.json"

# The gamut figure's resolution. Every third degree: 120 points is enough for a
# smooth curve at the width it is drawn and small enough to ship inline.
CURVE_STEP = 3

# The figure's geometry, in the SVG user units the template's viewBox uses.
# It lives here rather than in the template because the polyline is computed
# here: two copies of a coordinate system is how a curve ends up drawn half a
# plot off its own axis labels.
PLOT_X0, PLOT_X1 = 56.0, 704.0
PLOT_Y0, PLOT_Y1 = 24.0, 152.0
PLOT_C_MAX = 120.0

# The hues the figure calls out by name, and why each is worth a marker.
MARKERS = (
    (330.0, "330 deg - the brand"),
    (216.0, "216 deg - scene-01"),
)

# B1. One number, written once, and the only input this script takes.
BRAND_HUE = 330.0

# The roles, in the order they are emitted, with the one-line reason each is
# in the stylesheet at all. A role nobody uses should be deleted here rather
# than left for a reader to wonder about.
ROLES = (
    ("surface", "the ground; everything else is measured against it"),
    ("on_surface", "all body text, at one lightness (hierarchy is size and weight)"),
    ("primary", "the accent: wordmark, links, focus ring"),
    ("secondary", "metadata beside the accent, where full chroma would shout"),
    ("tertiary", "the cost clauses, which must not read as an error"),
    ("outline", "rules and borders only -- never type"),
    ("error", "fixed by the theme; never tracks the hue"),
)


def render() -> str:
    palette = sc.build_palette(BRAND_HUE)
    surface = cm.hex_to_rgb(palette["surface"]["hex"])

    lines = [
        "// Generated by tools/scene-check/emit_web_tokens.py -- do not edit.",
        "//",
        "// The hue is docs/decisions/b1-brand-hue.md; everything else is",
        "// tools/scene-check/scene_check.py's build_palette(), the same function",
        "// the theme derives a scene's palette with. Re-run with --write after",
        "// changing the band, the chroma cap or the contrast floor; CI runs",
        "// --check so a stale copy of this file fails a pull request.",
        "//",
        f"// Hue {BRAND_HUE:g} deg. Contrast ratios are against surface, measured here.",
        "",
        ":root {",
    ]

    for role, why in ROLES:
        entry = palette[role]
        hex6 = entry["hex"]
        lightness, chroma, hue = cm.rgb_to_lch(cm.hex_to_rgb(hex6))
        name = role.replace("_", "-")
        if role == "surface":
            note = why
        else:
            ratio = cm.contrast(cm.hex_to_rgb(hex6), surface)
            note = f"{why} -- {ratio:.2f}:1"
        lines.append(f"  // {note}")
        lines.append(f"  --{name}: #{hex6}; // lch({lightness:.0f}% {chroma:.0f} {hue:.0f})")

    # Two lifted surfaces for cards and rules. They are not palette roles --
    # build_palette() does not define them -- so they are derived here, openly,
    # by walking the surface up in L* at its own chroma. Doing it in code
    # rather than pasting two hexes keeps them correct if the surface moves.
    lines.append("")
    lines.append("  // Lifted grounds. Not palette roles: derived here from surface,")
    lines.append("  // +6 and +12 in L*, so they follow it if it ever moves.")
    s_l, s_c, s_h = cm.rgb_to_lch(surface)
    for step, name in ((6.0, "surface-2"), (12.0, "surface-3")):
        # lch_to_rgb_clipped returns the chroma it could actually keep, which
        # is reported rather than discarded: a lifted ground that silently lost
        # chroma is how a near-neutral turns grey without anyone noticing.
        lifted, used = cm.lch_to_rgb_clipped(s_l + step, s_c, s_h)
        hex6 = cm.rgb_to_hex(lifted)
        lines.append(f"  --{name}: #{hex6}; // lch({s_l + step:.0f}% {used:.0f} {s_h:.0f})")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_curve() -> str:
    """The accent sRGB allows at every third hue, as the site plots it.

    This is the figure that makes B1 arguable rather than asserted: it shows
    330 deg sitting on the chroma plateau and scene-01's 216 deg at the bottom
    of the 180-250 trough. Generated for the same reason the tokens are -- a
    hand-pasted array of 120 triples is a place for invented numbers to hide,
    and once did exactly that.
    """
    points = []
    for tenths in range(0, 3600, CURVE_STEP * 10):
        hue = tenths / 10
        primary = sc.build_palette(hue)["primary"]
        points.append([hue, round(primary["C_used"], 1), primary["hex"]])

    rows = ",\n".join(f'  [{h:g}, {c}, "{hexes}"]' for h, c, hexes in points)

    # The polyline and the gradient are computed here, not in the template and
    # not in the browser, so the figure is in the HTML that is served. A chart
    # that needs JavaScript to exist is a chart that is missing from a reader's
    # print, reader mode and first paint; script only adds the hover readout.
    polyline = " ".join(f"{_px(h):.1f},{_py(c):.1f}" for h, c, _ in points)

    # Gradient stops as data, not as markup. The template builds the <stop>
    # elements; this file should not know what SVG looks like, and a string of
    # pre-rendered tags in a JSON file is markup smuggled past review.
    stops = ",\n".join(
        f'  {{"offset": {h / 360 * 100:.1f}, "hex": "{hexes}"}}' for h, _, hexes in points[::2]
    )
    markers = ",\n".join(
        "  "
        + json.dumps(
            {
                "hue": h,
                "label": label,
                "x": round(_px(h), 1),
                "y": round(_py(_chroma_at(points, h)), 1),
                "chroma": _chroma_at(points, h),
                "hex": _hex_at(points, h),
            }
        )
        for h, label in MARKERS
    )

    return (
        "{\n"
        f' "step": {CURVE_STEP},\n'
        f' "c_max": {PLOT_C_MAX:g},\n'
        f' "plot": {{"x0": {PLOT_X0:g}, "y0": {PLOT_Y0:g}, '
        f'"x1": {PLOT_X1:g}, "y1": {PLOT_Y1:g}}},\n'
        f' "polyline": {json.dumps(polyline)},\n'
        f' "stops": [\n{stops}\n ],\n'
        f' "markers": [\n{markers}\n ],\n'
        f' "points": [\n{rows}\n ]\n'
        "}\n"
    )


def _px(hue: float) -> float:
    return PLOT_X0 + (PLOT_X1 - PLOT_X0) * hue / 360.0


def _py(chroma: float) -> float:
    return PLOT_Y1 - (PLOT_Y1 - PLOT_Y0) * chroma / PLOT_C_MAX


def _chroma_at(points: list, hue: float) -> float:
    return min(points, key=lambda p: abs(p[0] - hue))[1]


def _hex_at(points: list, hue: float) -> str:
    return min(points, key=lambda p: abs(p[0] - hue))[2]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the stylesheet")
    group.add_argument("--check", action="store_true", help="fail if it is out of date")
    args = ap.parse_args()

    outputs = ((OUT, render()), (CURVE, render_curve()))

    if args.write:
        for path, text in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
        return 0

    stale = False
    for path, text in outputs:
        if not path.exists():
            print(f"missing {path.relative_to(ROOT)}", file=sys.stderr)
            stale = True
            continue
        current = path.read_text(encoding="utf-8")
        if current == text:
            print(f"{path.relative_to(ROOT)} is current")
            continue
        stale = True
        print(f"{path.relative_to(ROOT)} is stale:", file=sys.stderr)
        diff = difflib.unified_diff(
            current.splitlines(), text.splitlines(), "committed", "generated", lineterm=""
        )
        print("\n".join(diff), file=sys.stderr)

    if stale:
        # Say which direction to fix it in. A diff that leaves the reader
        # guessing whether to edit the file or the generator invites editing
        # the file, which is how a generated file stops being generated.
        print(file=sys.stderr)
        print("The generator is the authority. Run", file=sys.stderr)
        print("  python3 tools/scene-check/emit_web_tokens.py --write", file=sys.stderr)
        print("and commit the result. Do not edit these files by hand.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

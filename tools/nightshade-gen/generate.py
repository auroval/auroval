#!/usr/bin/env python3
"""nightshade-gen — generate a scene candidate from a recorded brief.

This exists because it did not. scene-01 was generated by a script in a
scratch directory which was then thrown away, and its `source.md` says
*"everything needed to regenerate this image byte-for-byte is below"* while
recording only the style and subject clauses. The other seven clauses — §4.1's
blockquote and §4.2's bullets — were assembled at runtime by that script, so
scene-01's full prompt is **not recoverable** and that claim is currently
false. It becomes true for scene-02 onwards because the assembly is here.

Run:
    python3 tools/nightshade-gen/generate.py BRIEF.json OUTDIR
    python3 tools/nightshade-gen/generate.py BRIEF.json OUTDIR --seeds 1,3,7
    python3 tools/nightshade-gen/generate.py BRIEF.json OUTDIR --dry-run

A brief is the per-scene variable part and nothing else:

    {"tag": "shrine", "subject": "a small weathered stone roadside shrine ..."}

`style` is not a field. It is a theme constant (§4.1.1), it lives in this
file, and a brief that tries to set it is refused — "two scenes drawn in
different styles do not read as one theme" is the whole reason that section
exists, and a per-scene override would quietly undo it.

Output per seed, into OUTDIR:
    <tag>-s<seed>-master16.png   the 16-bit master, what the loop renderer eats
    <tag>-s<seed>.png            8-bit, what scene_check.py and eyes read
    <tag>-s<seed>-run.json       prompt, settings, versions, resolved revision

--dry-run prints the assembled prompt and writes nothing. Use it to read what
the model will actually be told before spending ten minutes on it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# --------------------------------------------------------------------------
# The constant part of every nightshade prompt.
#
# docs/themes/nightshade-assets.md is the authority; these are transcribed
# from it with the section recorded beside each clause, which is the same
# arrangement tools/scene-check/scene_check.py uses for the contract's
# numbers. Transcription can drift from its source, so the section numbers
# are not decoration: they are how a reader checks.
# --------------------------------------------------------------------------

# §4.1.1 — the operative string, not the art-historical label.
STYLE = (
    "Sumi-e ink wash painting with bold calligraphic brushstrokes on toned "
    "paper, minimal flat colour accents, visible brush texture, no "
    "photographic realism"
)

# §4.1 — the constant part, as its blockquote has it.
CONSTANT = [
    "one subject, centred, filling the upper-middle of the frame, against darkness",
    "rim light and glow only, sourced from behind or beside the subject, no frontal key light",
    "saturated neon chroma, magenta and cyan and violet",
    "near-black field below and around the subject",
    "visible film grain",
    "16:9",
]

# §4.2 — the negative constraints, "these matter more than the positive ones",
# restated as positive assertions.
#
# Not for tidiness. FLUX.2-klein is a distilled model run at
# guidance_scale=1.0, which means no classifier-free guidance, which means
# there is no negative prompt for a "no X" to go into. Phrased as a negation
# in the positive prompt, "no glowing lamp" supplies the tokens for a glowing
# lamp and nothing to oppose them. Each bullet is therefore turned into a
# statement of what the frame does contain instead.
NEGATIVE_AS_POSITIVE = [
    # "No bright element in the centre of the frame" — the fatal one.
    "the centre of the frame is unlit and empty, the brightest areas are confined to the top of the image",
    # "No horizon line through the middle."
    "no ground plane and no horizon, only darkness behind and below the subject",
    # "Nothing important in the lower centre."
    "the lower middle of the frame is empty near-black space",
    # "No fine detail behind the text zone."
    "the darkness is a smooth flat gradient without fine detail",
]

# §4.1 — "No text, no logos, no watermark." Kept apart from the list above
# because it is not a composition clause and it is the one instruction a
# generator most reliably ignores, so it goes last, where it is least likely
# to be truncated away.
NO_MARKS = "no text, no lettering, no signature, no logo, no watermark"

# §3, §4.4 — settings. Identical to scene-01's, deliberately: a candidate that
# differs in subject *and* in settings tells you nothing about either.
MODEL = "black-forest-labs/FLUX.2-klein-4B"
REVISION = "e7b7dc27f91deacad38e78976d1f2b499d76a294"
STEPS = 4
GUIDANCE = 1.0
WIDTH, HEIGHT = 2560, 1440


def assemble(subject: str) -> str:
    """The full prompt, in the order the clauses are given to the model.

    Style first because it is the most visible thing about the image (§4.1.1),
    subject second, constraints last. That order is scene-01's as far as its
    record goes; it is recorded here so that the next scene does not have to
    guess at it the way this one did.
    """
    parts = [STYLE, subject, *CONSTANT, *NEGATIVE_AS_POSITIVE, NO_MARKS]
    return ". ".join(p.rstrip(" .,") for p in parts) + "."


def load_brief(path: Path) -> dict:
    brief = json.loads(path.read_text())
    if isinstance(brief, list):
        if len(brief) != 1:
            sys.exit(f"{path}: expected one brief, found {len(brief)}")
        brief = brief[0]
    if "style" in brief:
        sys.exit(
            f"{path}: a brief must not set 'style'. The rendering style is a "
            "theme constant (nightshade-assets.md §4.1.1) and lives in "
            "generate.py. Wanting a different style is wanting a different "
            "theme."
        )
    for field in ("tag", "subject"):
        if not brief.get(field):
            sys.exit(f"{path}: missing '{field}'")
    return brief


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("brief", type=Path)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("--seeds", default="1", help="comma-separated, default 1")
    ap.add_argument("--steps", type=int, default=STEPS)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    brief = load_brief(args.brief)
    prompt = assemble(brief["subject"])
    seeds = [int(s) for s in args.seeds.split(",") if s.strip()]

    print(f"tag     {brief['tag']}")
    print(f"seeds   {seeds}")
    print(f"size    {WIDTH}x{HEIGHT}  steps {args.steps}  guidance {GUIDANCE}")
    print(f"chars   {len(prompt)}")
    print()
    print(prompt)
    print()

    if args.dry_run:
        print("--dry-run: nothing generated")
        return

    # Imported here, not at the top: --dry-run is the way to read the prompt
    # before committing to the run, and it must not need torch installed to
    # do it.
    import cv2
    import numpy as np
    import torch
    from diffusers import Flux2KleinPipeline
    from PIL import Image

    args.outdir.mkdir(parents=True, exist_ok=True)

    print(f"loading {MODEL} @ {REVISION[:12]} ...", flush=True)
    pipe = Flux2KleinPipeline.from_pretrained(MODEL, revision=REVISION, torch_dtype=torch.bfloat16)
    # Not .to("cuda"): a 4B transformer plus its text encoder at 2560x1440
    # does not fit a consumer card alongside a compositor. Offloading costs
    # wall-clock and nothing else.
    pipe.enable_model_cpu_offload()

    import diffusers

    versions = {
        "diffusers": diffusers.__version__,
        "torch": torch.__version__,
        "cuda": torch.version.cuda,
        "device": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
    }

    for n, seed in enumerate(seeds, 1):
        stem = f"{brief['tag']}-s{seed}"
        print(f"[{n}/{len(seeds)}] seed {seed} -> {stem}", flush=True)
        out = pipe(
            prompt=prompt,
            width=WIDTH,
            height=HEIGHT,
            num_inference_steps=args.steps,
            guidance_scale=GUIDANCE,
            generator=torch.Generator("cpu").manual_seed(seed),
            output_type="np",
        ).images[0]

        # 16 bit from the VAE's float output, because the loop renderer
        # gradient-samples the master and 8-bit banding shows up in the
        # near-black field that is most of the frame.
        #
        # Written by cv2 and not by Pillow: Pillow's 16-bit support is
        # single-channel only (`I;16`), and `Image.fromarray` on a uint16
        # H*W*3 array raises `Cannot handle this data type: (1, 1, 3), <u2`.
        # cv2 writes 16-bit RGB PNG, and is already what nightshade-loop
        # uses, so the master is written by the same library that reads it.
        # cv2 is BGR, hence the channel reversal.
        a = np.clip(out, 0.0, 1.0)
        cv2.imwrite(
            str(args.outdir / f"{stem}-master16.png"),
            (a[:, :, ::-1] * 65535.0 + 0.5).astype(np.uint16),
        )
        # The 8-bit preview stays on Pillow, where RGB is the native case.
        Image.fromarray((a * 255.0 + 0.5).astype(np.uint8)).save(args.outdir / f"{stem}.png")
        (args.outdir / f"{stem}-run.json").write_text(
            json.dumps(
                {
                    "tag": brief["tag"],
                    "seed": seed,
                    "model": MODEL,
                    "revision": REVISION,
                    "steps": args.steps,
                    "guidance_scale": GUIDANCE,
                    "size": [WIDTH, HEIGHT],
                    "style": STYLE,
                    "subject": brief["subject"],
                    "prompt": prompt,
                    "versions": versions,
                },
                indent=2,
            )
            + "\n"
        )
        print(f"      wrote {stem}-master16.png, {stem}.png, {stem}-run.json")


if __name__ == "__main__":
    main()
